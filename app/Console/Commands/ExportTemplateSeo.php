                $typePrefix = "аккумуляторную ";
            } elseif (mb_strpos($titleLower, 'бензинов') !== false || mb_strpos($titleLower, 'бензо') !== false || mb_strpos($descLower, 'тип: бензинов') !== false) {
                $typePrefix = "бензиновую ";
            } elseif (mb_strpos($titleLower, 'электрическ') !== false || mb_strpos($titleLower, 'сетев') !== false || mb_strpos($titleLower, 'электро') !== false || mb_strpos($descLower, 'тип: электрическ') !== false) {
                $typePrefix = "электрическую ";
            } elseif (mb_strpos($titleLower, 'пневматическ') !== false) {
                $typePrefix = "пневматическую ";
            } elseif (mb_strpos($titleLower, 'ручн') !== false) {
                $typePrefix = "ручную ";
            }

            // Если товар мужского рода (например "Компрессор", "Триммер"), нужно поменять окончания
