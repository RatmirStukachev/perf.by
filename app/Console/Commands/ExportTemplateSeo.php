                ['{title}', '{category}', '{type}'], 
                [$product->title, $catName, $typePrefix], 
                $titleTemplates[array_rand($titleTemplates)]
            );
            $desc = str_replace(
                ['{title}', '{category}', '{type}'], 
                [$product->title, $catName, $typePrefix], 
                $descTemplates[array_rand($descTemplates)]
            );
            
            // Чистим возможные двойные пробелы (если тип пустой)
