            $desc = preg_replace('/\s+/', ' ', $desc);

            fputcsv($file, ['Product', $product->id, $product->title, $catName, $h1, mb_substr($title, 0, 255), mb_substr($desc, 0, 255)]);
        }

        $this->info("Обрабатываем категории...");
        $categories = Category::all();
        foreach ($categories as $category) {
            $h1 = $category->title;
            
            $title = str_replace(['{title}', '{category}', '{type}'], [$category->title, $category->title, ""], $titleTemplates[array_rand($titleTemplates)]);
            $desc = str_replace(['{title}', '{category}', '{type}'], [$category->title, $category->title, ""], $descTemplates[array_rand($descTemplates)]);
            
            $title = preg_replace('/\s+/', ' ', $title);
            $desc = preg_replace('/\s+/', ' ', $desc);

            fputcsv($file, ['Category', $category->id, $category->title, $category->title, $h1, mb_substr($title, 0, 255), mb_substr($desc, 0, 255)]);
        }

        fclose($file);
        $this->info("Готово! Файл создан: storage/app/seo_templates.csv");
